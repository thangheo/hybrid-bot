/**
 * @struct HawkesSignal
 * @brief Signal generated by the Hawkes process
 */
struct HawkesSignal {
    core::Direction direction;        // BUY or SELL
    double strength;            // Signal strength (0.0-1.0)
    double confidence;          // Confidence level (0.0-1.0)
    std::string reason;         // Reason for the signal
    double timestamp;           // Signal timestamp
};

/**
 * @class HawkesMarkovConfig
 * @brief Configuration for the Hawkes-Markov model
 */
class HawkesMarkovConfig {
public:
    uint32_t numStates = 20;                // Number of Markov states
    double markovLearningRate = 0.12;       // Learning rate for Markov transitions
    double hawkesBaseIntensity = 15.0;      // Base intensity for Hawkes process
    uint32_t eventWindowSize = 300;         // Maximum number of events to store
    double timeWindow = 3.0;                // Time window in seconds
    double alphaShort = 1.2;                // Short-term excitation coefficient
    double betaShort = 10.0;                // Short-term decay rate
    double alphaMedium = 0.5;               // Medium-term excitation coefficient
    double betaMedium = 1.5;                // Medium-term decay rate
    double alphaLong = 0.15;                // Long-term excitation coefficient
    double betaLong = 0.2;                  // Long-term decay rate
    double predictionThreshold = 0.65;      // Threshold for generating signals
    double marketRegimeThreshold = 0.3;     // Threshold for detecting regime changes
    
    // Excitation matrix (6x6 for the 6 event types)
    std::vector<std::vector<double>> excitationMatrix = {
        {0.7, 0.4, 0.2, 0.1, 0.5, 0.2},
        {0.4, 0.7, 0.1, 0.2, 0.2, 0.5},
        {0.2, 0.1, 0.5, 0.2, 0.3, 0.1},
        {0.1, 0.2, 0.2, 0.5, 0.1, 0.3},
        {0.6, 0.3, 0.4, 0.2, 0.8, 0.4},
        {0.3, 0.6, 0.2, 0.4, 0.4, 0.8}
    };
};

/**
 * @class HawkesMarkovDetector
 * @brief Implements Hawkes process and Markov model for order book analysis
 */
class HawkesMarkovDetector {
public:
    /**
     * @brief Constructor
     */
    HawkesMarkovDetector();
    
    /**
     * @brief Destructor
     */
    virtual ~HawkesMarkovDetector() = default;
    
    /**
     * @brief Initialize the detector with configuration
     * @param config Configuration parameters for the Hawkes-Markov model
     * @return True if initialization successful, false otherwise
     */
    bool initialize(const HawkesMarkovConfig& config);
    
    /**
     * @brief Process a new order book event
     * @param event The order book event to process
     * @param orderBook Current order book state
     * @param recentTrades Recent trades history
     * @return Processing time in milliseconds
     */
    double processEvent(const OrderBookEvent& event, 
                       const data_ingestion::OrderBook& orderBook,
                       const std::vector<OrderBookEvent>& recentTrades);
    
    /**
     * @brief Calculate the Hawkes intensity for a specific event type
     * @param eventType The event type to calculate intensity for
     * @param currentTime Current timestamp
     * @return Calculated intensity value
     */
    /**
     * @brief Predict the next state based on current state
     * @return Predicted next state ID
     */
    uint32_t predictNextState();
    
    /**
     * @brief Make a trading decision based on current model state
     * @param currentPrice Current price
     * @param currentTime Current timestamp
     * @return Trading signal or nullptr if no signal generated
     */
    HawkesSignal makeDecision(double currentPrice, double currentTime);
    
    /**
     * @brief Get current market state ID
     * @return Current state ID or -1 if not yet set
     */
    int32_t getCurrentState() const;
    
    /**
     * @brief Get prediction accuracy
     * @return Accuracy as a value between 0.0 and 1.0
     */
    double getPredictionAccuracy() const;
    
    /**
     * @brief Register callback for signals
     * @param callback Function to call when signal is generated
     * @return Callback ID
     */
    size_t registerSignalCallback(const std::function<void(const HawkesSignal&)>& callback);
    
    /**
     * @brief Unregister a callback
     * @param callbackId ID of the callback to unregister
     * @return True if successful, false otherwise
     */
    bool unregisterSignalCallback(size_t callbackId);
    double getDecayFactor(double dt, const std::string& decayType);
    /**
     * @brief Get the detector status
     * @return Status as a string
     */
    std::string getStatus() const;

private:
    // Configuration
    HawkesMarkovConfig config_;
    
    // Event buffer
    std::deque<OrderBookEvent> eventBuffer_;
    
    // Markov model state
    uint32_t currentState_;
    uint32_t previousState_;
    std::vector<std::vector<double>> transitionMatrix_;
    
    // Prediction tracking
    uint32_t lastPrediction_;
    std::deque<double> predictionErrors_;
    std::deque<uint32_t> predictions_;
    std::deque<uint32_t> actualOutcomes_;
    
    // Exponential decay lookup tables
    std::vector<double> expLookupShort_;
    std::vector<double> expLookupMedium_;
    std::vector<double> expLookupLong_;
    
    // Callbacks for signals
    std::map<size_t, std::function<void(const HawkesSignal&)>> callbacks_;
    size_t nextCallbackId_;
    
    // Mutex for thread safety
    mutable std::mutex mutex_;
    
    // Private helper methods
    uint32_t calculateMarketState(const data_ingestion::OrderBook& orderBook, 
                                 const std::vector<OrderBookEvent>& recentTrades);
    double calculateHawkesIntensity(uint8_t eventType, double currentTime) const;
    double getDecayFactor(double dt, const std::string& decayType) const;
    void initializeExpLookup();
    void notifySignalCallbacks(const HawkesSignal& signal);
};

